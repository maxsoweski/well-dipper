#!/usr/bin/env node
// scripts/gen-real-proper-names.mjs
//
// RUN:  node scripts/gen-real-proper-names.mjs
// Writes src/generation/data/realProperNames.js
//
// Extracts every single-token alphabetic proper star name from the shipped
// real-star catalog (public/assets/data/hyg-stars.json, HYG v4.0 — regenerated
// in increment 3a / AC9) and bakes them into a JS module used as a STRUCTURAL
// BLOCKLIST by NameGenerator's bare-fantasy-word class. This guarantees the
// procedural generator never emits a real star's proper name (design req (d) of
// the naming-census-uniqueness workstream, ac5-decision.md rule 2/§(d)).
//
// Why single-token only: the bare-fantasy class emits single capitalized words
// (e.g. "Lyreon"); the only real names it could ever collide with are single
// alphabetic tokens ("Sirius", "Vega", "Rigel"). Multi-token names ("Rigil
// Kentaurus", "Alp Cen") and designations ("HD 1234") have a different shape
// and can never be produced by the bare class, so they don't need blocklisting
// here. (The census tool cross-checks ALL procgen output against the full
// meaningful-name set separately.)
//
// Deterministic: pure function of the input JSON; no time/randomness.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

const HYG_PATH = fileURLToPath(new URL('../public/assets/data/hyg-stars.json', import.meta.url));
const OUT_PATH = fileURLToPath(new URL('../src/generation/data/realProperNames.js', import.meta.url));

const raw = JSON.parse(readFileSync(HYG_PATH, 'utf-8'));
const single = new Set();
for (const s of raw) {
  const n = s.name;
  if (!n || n === '"') continue;
  if (/^[A-Za-z]+$/.test(n)) single.add(n);
}
const arr = [...single].sort((a, b) => a.localeCompare(b));

const header =
`/**
 * Real single-token proper star names, extracted from public/assets/data/hyg-stars.json
 * (HYG v4.0, regenerated in increment 3a / AC9). Used as a structural blocklist so the
 * procedural bare-fantasy-word class never emits a real star's proper name (design req (d)).
 *
 * Generated by scripts/gen-real-proper-names.mjs — DO NOT hand-edit; re-run that script if the
 * HYG catalog is regenerated. Count: ${arr.length} single-token names.
 */
`;
const body =
`export const REAL_PROPER_NAMES = [
${arr.map(n => `  ${JSON.stringify(n)},`).join('\n')}
];

// Lowercased set for O(1) case-insensitive membership checks.
export const REAL_PROPER_NAME_SET = new Set(REAL_PROPER_NAMES.map(n => n.toLowerCase()));
`;

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, header + body);
console.log(`gen-real-proper-names: wrote ${OUT_PATH} with ${arr.length} single-token names`);
